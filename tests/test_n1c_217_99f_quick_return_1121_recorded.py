"""n1-c life-217's first 99F expedition (2026-11-21 12:28-12:29): the return to town from 99F.

Owner 2026-11-21 「99Fで急に帰った理由」.  Recorded (capture n1c-217-20261121-99f-quick-return):
the finale's recall landed on 95F (the saved depth was 95), the stairs took the character to 99F
(12:29:03), the arrival sweep's *Destruction* teleported Oberon (a QUESTOR) away, the floor was
regenerated by its stairs (quest:regen:ascend, 99F -> 98F -> 99F), and on the new 99F the
detection showed Oberon (board 1991, a T1).  hunt_target's verdict latched the unviable-quest
return (``_latch_unviable_quest_return``, trigger quest-unviable), which opened the quest floor's
exit lock (``_quest_floor_exit_locked``: the unviable floor first); the return took the up stairs
under the arrival (return:ascend, 12:29:06) and read Word of Recall on 98F, where the finale's
recall rule does not reach.  The owner's rule 「帰還による離脱は成功時と魔力復活の薬を予定の倍以上
使ったときのみ」 had no say over a stair.  And the battle's memory (keyed by the floor key) kept the
earlier 99F level's on the regenerated one.

Fixture tests/fixtures/n1c-99f-quick-return-1121: the town-arrival checkpoint after that return
(12:29:10, the same character and gear) and three recorded state boards (``boards.json.xz``:
line 1984 the 98F of the regeneration, 1991 the new 99F with Oberon detected, 1994 the 99F board
the return took the up stairs from).

DECLARED CONSTRUCTED:
* the expedition's mark (finale_prep ``lifted``) on the restored policy, as during the trip, and
  no return latched on the arrival;
* hunt_target's unbeatable verdict on Oberon (the recorded trigger, quest-unviable);
* the earlier level's battle past its sweep (phase ``battle``, Oberon last seen at (5, 110)).
"""
import tests  # noqa: F401 -- isolate runtime files for a bare-module run

import contextlib
import io
import json
import lzma
import unittest
from pathlib import Path
from tempfile import TemporaryDirectory
from unittest import mock

from hengbot import angband_finale_battle, finale_prep, hunt_target, return_start
from hengbot.model import parse_snapshot
from support.town_arrival_fixture import load

FIXTURE = Path(__file__).with_name("fixtures") / "n1c-99f-quick-return-1121"


class N1c21799fQuickReturnRecordedTest(unittest.TestCase):
    def setUp(self):
        self.scratch = TemporaryDirectory()
        self.policy, _journal, _steps = load(FIXTURE, Path(self.scratch.name) / "fixture")
        self.addCleanup(self.policy._home_disposal.history_path.unlink, missing_ok=True)
        held = finale_prep.phase(self.policy)
        held.lifted, held.step = True, finale_prep.DONE  # DECLARED: the expedition's mark
        # DECLARED: no return latched on the arrival.
        self.policy._returning_to_town, self.policy._last_return_trigger = False, None
        # DECLARED: no list re-read at the decision's head (me_powers_refresh.resume_read_key
        # answers before the board is observed, so the 98F board would not be seen).
        self.policy._me_power_resume_reads = False
        rows = json.loads(lzma.decompress((FIXTURE / "boards.json.xz").read_bytes()))
        self.boards = {row["line"]: parse_snapshot(row["board"], self.policy._monrace_knowledge)
                       for row in rows}

    def tearDown(self):
        self.scratch.cleanup()

    def decide(self, line):
        board = self.boards[line]
        with contextlib.redirect_stdout(io.StringIO()):
            key = self.policy.choose_key(board)
        if key:
            self.policy.confirm_key_posted(key)
        return board

    def test_the_finale_floor_is_the_battles_and_no_unviable_quest_return_opens_it(self):
        board = self.boards[1994]
        self.assertEqual(board.floor_key, (1, 99, 0))
        self.assertTrue(angband_finale_battle.applies(self.policy, board))
        self.assertFalse(angband_finale_battle.recall_permitted(self.policy, board))
        # DECLARED: Oberon judged unbeatable (the recorded trigger).
        with mock.patch.object(hunt_target, "quest_target_unbeatable", return_value=True):
            self.policy._latch_unviable_quest_return(board, [])
        self.assertIsNone(self.policy._unviable_quest_floor)
        self.assertNotEqual(self.policy._last_return_trigger, "quest-unviable")
        self.assertTrue(self.policy._quest_floor_exit_locked(board))

    def test_a_latched_return_takes_no_stairs_off_the_finale_floor(self):
        board = self.boards[1994]
        here = board.grid_at(board.player.position)
        self.assertTrue(self.policy._is_upstairs_target(here))  # the arrival's up stairs
        # DECLARED: the recorded latch (unviable floor, return started).
        self.policy._unviable_quest_floor = board.floor_key
        return_start.start(self.policy, "quest-unviable")
        self.assertTrue(self.policy._quest_floor_exit_locked(board))
        with contextlib.redirect_stdout(io.StringIO()):
            key = self.policy._return_to_town_key(board, [])
        self.assertNotEqual(self.policy.last_reason, "return:ascend")
        self.assertIsNone(key)

    def test_the_regenerated_99f_starts_its_own_battle(self):
        self.decide(1991)  # the 99F with Oberon detected
        held = angband_finale_battle.battle(self.policy, self.boards[1991])
        held.phase, held.last_seen = angband_finale_battle.BATTLE, (5, 110)  # DECLARED
        self.decide(1984)  # 98F: the stairs of the regeneration
        board = self.decide(1994)  # 99F again, a new level under the same key
        fresh = angband_finale_battle.battle(self.policy, board)
        self.assertIsNot(fresh, held)
        self.assertIsNone(fresh.last_seen)  # nothing of the earlier level's Oberon


if __name__ == "__main__":
    unittest.main()
