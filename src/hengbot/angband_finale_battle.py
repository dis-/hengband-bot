def _approach_key(policy, snapshot, held: Battle) -> str | None:
    """「最後に対象をみた座標に向かって移動」.  A last-seen cell no walk reaches: toward the nearest
    exploration frontier closer to it than the player (a cell the board no longer shows, as after a
    *Destruction* forgot it: n1-b life-416 Angband 99F 2026-11-23 18:3x, Oberon last seen at
    (11,106) and the teleport's landing (6,46) on the far side of forgotten ground), else opened
    toward (the openers: the digger's route, else Stone to Mud, retreat_enclosure
    ``open_toward_key``), else along the line by walking and Stone to Mud (``_line_key``); only
    with none of these is it given up (the target is then ``lost`` and the floor searched)."""
    if held.last_seen is None:
        return None
    goal = Position(*held.last_seen)
    here = snapshot.player.position
    if here == goal:
        return None
    left = _left_cells(held, here)
    # Owner 2026-11-24 (verbatim) 「射線を通す近づき方をしたのが悪い。射線を通さないように近づくないし
    # 待つのがただしい」: with a strong non-target known (``shunned``) no step or melt of this walk
    # enters its line of fire; standing in one, the walk first steps out of it.  n1-b life-416
    # (Angband 100F, 05:24:27, seq 1214): at (9,25) the Serpent unseen (last seen (9,54)), the
    # Tarrasque in view at (9,40), the walk stepped '6' along row 9 into its line; its cold and
    # disenchantment breaths took 999 HP to 83.
    guarded = bool(shunned(policy, snapshot))
    if guarded and _exposed(policy, snapshot, here):
        out = _out_of_line_key(policy, snapshot, held)
        if out is not None:
            return out
    step = _route_step(policy, snapshot, lambda position: position == goal, avoid=left)
    if step is not None:
        key = policy._step_toward(snapshot, step)
        policy.last_reason = APPROACH_REASON
        return key
    distance = game_distance(here, goal)

    def frontier(position) -> bool:
        grid = snapshot.grids.get(position)
        return (grid is not None and game_distance(position, goal) < distance
                and policy._is_frontier(snapshot, grid))
    if guarded:
        first = _safe_step(policy, snapshot, frontier, avoid=left)
    else:
        route = policy._nearest_goal_route(
            snapshot, lambda grid: game_distance(grid.position, goal) < distance
            and policy._is_frontier(snapshot, grid))
        first = route.first_step if route is not None and route.first_step not in left else None
    if first is not None:
        key = policy._step_toward(snapshot, first)
        policy.last_reason = APPROACH_REASON
        return key
    from hengbot import quest_target_search, retreat_enclosure  # import cycle
    # The openers walk and melt by routes of their own, which no line of fire is asked of: with
    # a strong non-target known they are not asked (the line below asks each step and melt).
    opened = None if guarded else retreat_enclosure.open_toward_key(
        policy, snapshot, quest_target_search.walkable_cells(policy, snapshot), {goal})
    if opened is not None:
        return opened
    # The openers' routes run over known grids only; a last-seen cell in forgotten ground is
    # reached along the line instead (``_line_key``; owner 2026-11-21 「岩石溶解の消費量は問題では
    # ない」).  n1-b life-416 (Angband 99F, 2026-11-23 21:08, seq 204): at (3,62), Oberon last seen
    # at (11,120) beyond ground the *Destruction*s had forgotten, the cell was dropped and the floor
    # searched from x 16-63 until it was regenerated without him.
    line = _line_key(policy, snapshot, goal, avoid=left)
    if line is not None:
        return line
    if guarded:
        # No way that keeps out of the strong non-targets' lines: wait out of them (never given up
        # for them: the cell is kept).
        return _out_of_line_key(policy, snapshot, held)
    # Only with no way at all (no melt in hand, blind or confused, every nearer neighbour a
    # permanent or worn-out wall) is the cell given up; the case is kept for the decision record.
    held.dropped = (snapshot.turn, held.last_seen, _line_refusal(policy, snapshot))
    held.last_seen = None
    return None


def _left_cells(held: Battle, here: Position) -> frozenset:
    """The cells the walk to the last-seen cell has stood on and left (``Battle.trail``), with
    ``here`` noted; a new last-seen cell starts a new trail.

    Owner 2026-11-13 「交互に逆へ歩くループは根から防ぐ」: the walk's rungs disagree from one cell to
    the next -- the frontier walk's route is drawn anew on each board under the walk vetoes of
    that board, and ``_line_key`` steps only nearer -- so no step of the walk enters a cell it
    left.  Every step enters a new cell, so the walk cannot cycle.  n1-b life-416 (Angband 100F,
    2026-11-24 04:34:47-59, seq 4979-4987, loop-detected): at (10,27), 65 from the Serpent's
    last-seen (10,92), the frontier route to (13,55) stepped '1' to (11,26); there no route was
    drawn and the line stepped '9' back to (10,27), eight times."""
    cell = (here.y, here.x)
    if held.trail_goal != held.last_seen:
        held.trail_goal, held.trail = held.last_seen, set()
    held.trail.add(cell)
    return frozenset(Position(y, x) for y, x in held.trail if (y, x) != cell)


def _line_refusal(policy, snapshot) -> str:
    """Why ``_line_key`` found no step (the decision record's ``dropped``)."""
    from hengbot import sealed_pocket  # import cycle
    player = snapshot.player
    if player.blind or player.confused:
        return "blind-or-confused"
    if not sealed_pocket.can_melt(policy, snapshot):
        return "no-melt"
    return "no-nearer-cell"


def _line_key(policy, snapshot, goal: Position, *, keep: int = 0, target=None,
              avoid=frozenset()) -> str | None:
    """One step along the line toward ``goal`` where no walk reaches it: the walkable neighbour
    nearest to it, else Stone to Mud aimed at the nearest known wall (a beam melts the adjacent
    wall), each strictly nearer to ``goal`` than the player and no nearer than ``keep`` (the
    target's teleport distance stays outside it).  With ``target``, a melt that would open the line
    of fire on it where it stands is not made (``_opens_line``, owner 2026-11-21 LOCKED
    「溶かした時に先手を取られて何も出来ず離脱している場面が問題」).  Every step is nearer, so the
    approach never turns back on itself; None when no neighbour qualifies."""
    from hengbot import retreat_enclosure, sealed_pocket  # import cycle
    here = snapshot.player.position
    distance = game_distance(here, goal)
    if distance <= keep:
        return None
    walkable = set(policy._walkable_neighbors(snapshot, here, allow_damaging=False))
    guarded = bool(shunned(policy, snapshot))
    options = []
    for dy, dx in DIRECTIONS:
        cell = Position(here.y + dy, here.x + dx)
        nearer = game_distance(cell, goal)
        if nearer >= distance or nearer < keep:
            continue
        # Equal game distances (its halved minor axis) are told apart by the straight line.
        line = (goal.y - cell.y) ** 2 + (goal.x - cell.x) ** 2
        if cell in walkable:
            # A cell the walk left (``_left_cells``), or one in a strong non-target's line of fire
            # (``_exposed``, owner 2026-11-24 「射線を通さないように近づく」).
            if cell not in avoid and not (guarded and _exposed(policy, snapshot, cell)):
                options.append((nearer, line, 0, cell.y, cell.x))
            continue
        grid = snapshot.grids.get(cell)
        if grid is not None and grid.known and retreat_enclosure.meltable(policy, snapshot, grid):
            options.append((nearer, line, 1, cell.y, cell.x))
    for _nearer, _line, melt, y, x in sorted(options):
        cell = Position(y, x)
        if not melt:
            policy.last_reason = APPROACH_REASON
            return policy._step_toward(snapshot, cell)
        if target is not None and _opens_line(policy, snapshot, here, cell, target.position):
            continue
        if guarded and _melt_exposes(policy, snapshot, cell):
            continue
        key = sealed_pocket.melt_at_key(policy, snapshot, cell, MELT_REASON)
        if key is not None:
            return key
    return None


def _detect_key(policy, snapshot, held: Battle) -> str | None:
    """Owner 2026-11-23 「着いた所で全感知し見えなければ最後の位置へ歩く」: once where a teleport landed
    and once on reaching the last-seen cell, the full detection while the target is shown nowhere:
    the absorbed Detection (else Detect Evil for an EVIL target), else a carried Rod of Detection or
    Staff of Detect Evil.  With none to use the walk goes on."""
    from hengbot import area_mapping, hunt_target, quest_target_search  # import cycle
    from hengbot.item_reservation import reserved_item_command
    from hengbot.me_absorbed_substitutes import DETECTION, cast
    held.detect_due = False
    race = angband_finale.target_race(snapshot)
    flags = hunt_target.race_flags(policy, race) if race is not None else frozenset()
    for ident, effect in zip(DETECTION, ("detect-all", "detect-evil")):
        if not hunt_target.REVEALS[effect](flags):
            continue
        key = cast(policy, snapshot, ident, DETECT_REASON)
        if key is not None:
            return key
    if not area_mapping.device_usable_now(policy, snapshot):
        return None
    for (tval, sval), (kind, effect) in quest_target_search.CARRIED_DETECTION.items():
        item = next((each for each in snapshot.inventory
                     if (each.tval, each.sval) == (tval, sval)), None)
        if (item is None or not hunt_target.REVEALS[effect](flags)
                or not area_mapping.device_ready(item, kind)):
            continue
        key = reserved_item_command(policy, snapshot, kind, item)
        if key is not None:
            policy.last_reason = DETECT_REASON
            return key
    return None


