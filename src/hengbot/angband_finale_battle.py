def _fight_key(policy, snapshot, held: Battle, target) -> str | None:
    from hengbot import haste_read, line_of_fire, resist_potion, speed_dose
    if not haste_read.hasted(policy, snapshot):
        dose = speed_dose.key(policy, snapshot, HASTE_REASON)
        if dose is not None:
            return dose
    if not resist_potion.covered(snapshot.player):
        drink = resist_potion.quaff_key(policy, snapshot, RESIST_REASON)
        if drink is not None:
            return drink
    if line_of_fire.player_reaches(policy, snapshot, target):
        if rocket_charges(policy, snapshot) <= 0:
            return _restore_mana(policy, snapshot, empty=True)
        if not fire_hp_holds(snapshot):
            # Owner 2026-11-20 Q3: the heal outside the *Healing* rule (absorbed first) raises the
            # HP to the shot's 800 + cost.
            return _heal(policy, snapshot)
        held.stand = None
        return _rocket(policy, snapshot, target)
    # The target's own line is the tactic's (the stand, 先手); a strong non-target's is never
    # entered (owner 2026-11-24 「射線を通さないように近づくないし待つ」, 「サーペントには射線を通さなければ
    # ならない。混同しないように注意」): standing in one, step out of it first.
    guarded = bool(shunned(policy, snapshot))
    if guarded and _exposed(policy, snapshot, snapshot.player.position):
        out = _out_of_line_key(policy, snapshot, held)
        if out is not None:
            return out
    if held.stand is None:
        resurveyed = _resurvey_key(policy, snapshot, held, target)
        if resurveyed is not None:
            return resurveyed
    stood = _stand_key(policy, snapshot, held, target)
    if stood is not None:
        return stood
    closed = _close_in_key(policy, snapshot, target)
    if closed is not None:
        return closed
    # Owner 2026-11-24 「周辺感知で状況を確認する」: no stand and no nearer cell -- map the ground
    # around (the absorbed map, else a carried device or scroll) where no map of this floor covers
    # the player yet; the stand is chosen again on the mapped board.
    surveyed = _survey_key(policy, snapshot)
    if surveyed is not None:
        return surveyed
    if guarded:
        out = _out_of_line_key(policy, snapshot, held)
        if out is not None:
            return out
    return _wait_key(policy, snapshot, held)


def _close_in_key(policy, snapshot, target) -> str | None:
    """No stand on the target's rays is open or reachable yet (the rays run through ground the
    board does not know): the battle closes in itself, never nearer than ``STAND_MIN_DISTANCE``,
    so that the rays' cells come into the board and ``_stand_key`` takes over -- the walk to a
    nearer cell, else along the line by walking and Stone to Mud (``_line_key``, a melt that would
    open the line on the target where it stands not made).  n1-b life-416 (Angband 99F,
    2026-11-23 21:08, seq 160-176): Oberon detected 19 cells away with every ray in forgotten
    ground, the stand answered None and the generic hunt walked the player beside him; at
    distance 1 the battle had to teleport (seq 177).  None only when neither has a step; the
    ladder below answers then."""
    here = snapshot.player.position
    aim = target.position
    distance = game_distance(here, aim)
    def nearer(position) -> bool:
        grid = snapshot.grids.get(position)
        return (grid is not None and grid.known and grid.passable
                and STAND_MIN_DISTANCE <= game_distance(position, aim) < distance)
    step = _route_step(policy, snapshot, nearer)
    if step is not None:
        key = policy._step_toward(snapshot, step)
        policy.last_reason = APPROACH_REASON
        return key
    return _line_key(policy, snapshot, aim, keep=STAND_MIN_DISTANCE, target=target)


def key(policy, snapshot) -> str | None:
    """The finale's answer on this board, else None (the ladder below)."""
    small = _small_floor(policy, snapshot)
    if small is not None:
        return small
    if not applies(policy, snapshot):
        return None
    held = battle(policy, snapshot)
    _observe(policy, snapshot, held)
    player = snapshot.player
    if recall_permitted(policy, snapshot):
        recall = _recall(policy, snapshot)
        if recall is not None:
            return recall
    target = target_monster(snapshot)
    distance = game_distance(player.position, target.position) if target is not None else None
    if held.attacked and player.hp < STAR_HEAL_BELOW:
        healed = _quaff(policy, snapshot, angband_finale.STAR_HEALING, STAR_HEAL_REASON)
        if healed is not None:
            return healed
    if (held.summoned or (player.hp < TELEPORT_BELOW and (held.attacked or held.hit_below))
            or (distance is not None and distance <= TELEPORT_WITHIN)
            or crowded(policy, snapshot, target)):
        away = _teleport(policy, snapshot)
        if away is not None:
            held.phase, held.stand = RECOVER, None
            held.hit_below = False
            held.refused.clear()
            held.detect_due = True
            held.trail_goal = None  # the walk from the landing starts a new trail (``_left_cells``)
            return away
    eaten = _eat_key(policy, snapshot)
    if eaten is not None:
        return eaten
    if held.phase == SWEEP:
        swept = _sweep_key(policy, snapshot, held)
        if swept is not None:
            return swept
    if held.phase == RECOVER:
        recovered = _recover_key(policy, snapshot, held)
        if recovered is not None:
            return recovered
    # The full detection where the teleport landed (after the recovery's heal, which the
    # owner's 2026-11-20 line puts first) and on the last-seen cell (owner 2026-11-23).
    if held.detect_due and target is None and held.phase != SWEEP:
        detected = _detect_key(policy, snapshot, held)
        if detected is not None:
            return detected
    mapped = _map_key(policy, snapshot)
    if mapped is not None:
        return mapped
    cleared = _clear_key(policy, snapshot, held)
    if cleared is not None:
        return cleared
    if target is not None:
        return _fight_key(policy, snapshot, held, target)
    approach = _approach_key(policy, snapshot, held)
    if approach is not None:
        return approach
    searched = _lost_key(policy, snapshot)
    if searched is not None:
        return searched
    # The battle keeps the board (``_wait_key``): no generic rung answers on its floor.
    return _wait_key(policy, snapshot, held)


def _small_floor(policy, snapshot) -> str | None:
    """The option before the descent: on an Angband floor of the 95F exploration or deeper,
    short of 99F (angband_finale ``small_floor_key``)."""
    from hengbot.model import DUNGEON_ANGBAND
    if (snapshot.in_town or snapshot.floor_key[0] != DUNGEON_ANGBAND
            or snapshot.dungeon_level < angband_finale.PREPARE_DEPTH):
        return None
    return angband_finale.small_floor_key(policy, snapshot)
