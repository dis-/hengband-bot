def battle(policy, snapshot) -> Battle:
    held = getattr(policy, MEMORY, None)
    if held is None or held.floor != snapshot.floor_key:
        held = Battle(floor=snapshot.floor_key, prev_hp=snapshot.player.hp,
                      done_on_arrival=angband_finale.quest_done(snapshot))
        setattr(policy, MEMORY, held)
    return held


def applies(policy, snapshot) -> bool:
    """The battle owns this board: a 99F/100F floor of the finale's expedition whose quest was
    still TAKEN when the floor was first seen.  A floor whose quest was already done on arrival
    has nothing to fight and is no success to recall on: the expedition goes on down (n1-b
    life-411 2026-11-21 14:25:30 and 14:36:55: Oberon already killed, every arrival on 99F read
    the success recall at once and the 100F was never reached)."""
    if not (angband_finale.magic_eater(snapshot) and angband_finale.lifted(policy)
            and angband_finale.on_finale_floor(snapshot)):
        return False
    return not battle(policy, snapshot).done_on_arrival


def keeps_scrolls(policy, snapshot) -> bool:
    """A floor whose Teleportation scrolls are the battle's alone: one the battle holds
    (``applies``), or the relay floor above it while the stairs regenerate it (policy
    ``_quest_regen_phase``, the 98F above 99F and the 99F above 100F).  The owner's 2026-11-20
    directive reads the scroll on its own cases only (「召喚または攻撃を受けてHPが800を下回ったとき、
    または対象が距離2より近づいたとき」), and 2026-11-21 「巻物が尽きたら取り込んだテレポートの杖、杖も
    尽きたら帰還して補給」: the generic stuck escapes (sealed_pocket ``destroyed_leave_key``, policy
    ``_stuck_escape_key``) read none here.  n1-b life-416 (Angband 99F, 2026-11-23 18:30-18:46):
    11 stuck:destroyed-circle-teleport and 4 stuck:teleport-escape reads of the 39 scrolls; the
    empty pack recalled the character with Oberon alive."""
    if applies(policy, snapshot):
        return True
    return (not snapshot.in_town and angband_finale.magic_eater(snapshot)
            and angband_finale.lifted(policy)
            and snapshot.floor_key[0] == angband_finale.DUNGEON_ANGBAND
            and snapshot.dungeon_level + 1 in angband_finale.FINALE
            and getattr(policy, "_quest_regen_phase", None) in ("ascend", "descend"))


def _known_hostiles(snapshot) -> list:
    seen = {}
    for monster in (*snapshot.visible_monsters, *snapshot.detected_monsters):
        if monster.hostile and monster.index not in seen:
            seen[monster.index] = monster
    return list(seen.values())


def target_monster(snapshot):
    race = angband_finale.target_race(snapshot)
    return next((monster for monster in _known_hostiles(snapshot) if monster.race_id == race), None)


def others(snapshot) -> list:
    race = angband_finale.target_race(snapshot)
    return [monster for monster in _known_hostiles(snapshot) if monster.race_id != race]


def crowded(policy, snapshot, target) -> bool:
    """「ターゲットとターゲット以外が同時に射線に入っているとき」: a line projects from the player to
    the target and to another known monster on this board."""
    from hengbot import line_of_fire
    if target is None:
        return False
    here = snapshot.player.position
    return (line_of_fire.player_projectable(policy, snapshot, here, target.position)
            and any(line_of_fire.player_projectable(policy, snapshot, here, monster.position)
                    for monster in others(snapshot)))


def _observe(policy, snapshot, held: Battle) -> None:
    from hengbot import me_powerful_activation, summon_response  # import cycle
    hp = snapshot.player.hp
    # The Powerful Activation's own HP cost is no hit (me_powerful_activation ``own_cost``).
    held.attacked = (held.prev_hp is not None and hp < held.prev_hp
                     and not me_powerful_activation.own_cost(policy, snapshot))
    held.prev_hp = hp
    held.summoned = any(summon_response.summons_of(message) for message in snapshot.messages)
    target = target_monster(snapshot)
    if target is not None:
        held.last_seen = (target.position.y, target.position.x)
        # 「感知で回る」 counts a lap only after the target is lost (quest_target_search
        # ``restart_finale_lap``): the coverage made before this sighting is spent.
        from hengbot import quest_target_search  # import cycle
        quest_target_search.restart_finale_lap(policy, snapshot)
    elif held.last_seen is not None and snapshot.player.position == Position(*held.last_seen):
        # 「最後に対象をみた座標に向かって移動」 done and the target not there: detect again here
        # (owner 2026-11-23 「着いた所で全感知し見えなければ最後の位置へ歩く」), then it is lost, and
        # the floor is searched by detection (quest_target_search ``finale_searching``).
        held.last_seen = None
        held.detect_due = True


def lost(policy, snapshot) -> bool:
    """「感知で回る」: past the arrival sweep the target is shown nowhere and no last-seen cell is
    kept (quest_target_search searches the floor for it then)."""
    held = getattr(policy, MEMORY, None)
    return (applies(policy, snapshot) and held is not None and held.floor == snapshot.floor_key
            and held.phase != SWEEP and held.last_seen is None
            and target_monster(snapshot) is None)


