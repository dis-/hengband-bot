# -- the stand (Stone to Mud) ------------------------------------------------------------

def _grid(snapshot, cell):
    return snapshot.grid_at(Position(*cell))


def _open(grid) -> bool:
    return grid is not None and grid.known and grid.passable and not grid.wall


def _walls_between(snapshot, stand: Stand) -> list | None:
    """The cells between the stand and the aim that stop the Rocket (a wall, an unknown grid),
    nearest the stand first; None when one of them cannot be melted (a permanent wall)."""
    walls = []
    for k in range(stand.distance - 1, 0, -1):
        cell = (stand.aim[0] + stand.step[0] * k, stand.aim[1] + stand.step[1] * k)
        grid = _grid(snapshot, cell)
        if grid is not None and grid.known and getattr(grid, "permanent", False):
            return None
        if not _open(grid):
            walls.append(cell)
    return walls


def _candidates(policy, snapshot, aim, *, unshown: bool = False) -> list:
    """The stands on the target's eight rays (an open cell the board shows).  ``unshown``: a cell
    the board does not show (or a wall Stone to Mud melts) may be one too -- the way around
    (``_around_way``) opens it on arrival -- for a board that shows no stand at all."""
    from hengbot import retreat_enclosure, sealed_pocket  # import cycle
    charges = sealed_pocket.melt_charges(policy, snapshot)
    found = []
    for step in DIRECTIONS:
        for distance in range(ROCKET_RANGE, STAND_MIN_DISTANCE - 1, -1):
            cell = (aim[0] + step[0] * distance, aim[1] + step[1] * distance)
            grid = _grid(snapshot, cell)
            if not _open(grid) and not (unshown and (
                    (grid is None or not grid.known) and 0 < cell[0] < snapshot.height - 1
                    and 0 < cell[1] < snapshot.width - 1
                    or grid is not None and retreat_enclosure.meltable(policy, snapshot, grid))):
                continue
            stand = Stand(cell, aim, step, distance)
            walls = _walls_between(snapshot, stand)
            if walls is None or len(walls) > charges:
                continue
            # Owner 2026-11-21 (verbatim, an allowed simplification) 「必要なら問題の単純化のため、対象と
            # x軸かy軸を合わせて待ち、対象の動きを予測しやすくすると良い」: the target's row or column
            # first; then 「なるべく距離をとって」: the farthest, then the fewest walls.
            diagonal = step[0] != 0 and step[1] != 0
            found.append(((diagonal, -distance, len(walls)), stand))
    found.sort(key=lambda pair: pair[0])
    return [stand for _, stand in found]


def _choose_stand(policy, snapshot, aim) -> Stand | None:
    here = (snapshot.player.position.y, snapshot.player.position.x)
    held = battle(policy, snapshot)
    rays = _candidates(policy, snapshot, aim)
    candidates = [stand for stand in rays if (stand.cell, aim) not in held.refused]
    refused = len(rays) - len(candidates)
    if shunned(policy, snapshot):
        # Owner 2026-11-24 「射線を通さないように近づく」: no stand in a strong non-target's line.
        candidates = [stand for stand in candidates
                      if not _exposed(policy, snapshot, Position(*stand.cell))]
    exposed = len(rays) - refused - len(candidates)
    # Every candidate the walk reaches, best first: one search of the reachable cells, not a route
    # per candidate.  Owner 2026-11-24 (verbatim) 「周辺感知で状況を確認する。今回の場合は永久岩に
    # 阻まれていたので回り込む必要があった。」: the best rays may run into permanent rock (no melt
    # opens it, ``_walls_between``) or stand behind it; a stand around it is taken (n1-c life-221
    # Angband 100F 2026-11-24 07:18: only the six best were tried, none reached, and the battle
    # answered None beside the Serpent).
    reach = _reach(policy, snapshot)
    for stand in candidates:
        if stand.cell == here or Position(*stand.cell) in reach:
            return stand
    # None a walk reaches: the stand the cheapest way around reaches (``_around_way``).
    by_cell = {Position(*stand.cell): stand for stand in candidates}
    if not rays:
        # The board shows no stand on any ray (n1-c life-221 Angband 100F 2026-11-24 09:55: after
        # a restart the map memory was gone, the ground west of the vault unshown): the rays'
        # unshown cells and meltable walls are stands to reach and open (owner 2026-11-24
        # 「周辺感知で状況を確認する。…回り込む必要があった。」, the map first: ``_survey_key``).
        by_cell = {Position(*stand.cell): stand
                   for stand in _candidates(policy, snapshot, aim, unshown=True)
                   if not (shunned(policy, snapshot)
                           and _exposed(policy, snapshot, Position(*stand.cell)))}
    way = _around_way(policy, snapshot, by_cell)
    if way is not None:
        return by_cell[way[0]]
    # For the decision record: why no stand (the rays' cells within reach of the melts, those the
    # 先手 rule gave up, those in a strong non-target's line, and none of the rest reached).
    held.no_stand = (f"rays={len(rays)} refused={refused} exposed={exposed} "
                     f"unreached={len(candidates)} reach={len(reach)}")
    return None


def _reach(policy, snapshot) -> frozenset:
    """The cells the battle's walks reach on this board (``_route_step``'s walk: every walker's
    veto, and with a strong non-target known no cell in its line of fire)."""
    from collections import deque
    from hengbot.item_reservation import decision_memo

    def compute():
        start = snapshot.player.position
        veto = _battle_veto(policy, snapshot)
        guarded = bool(shunned(policy, snapshot))
        seen = {start}
        queue = deque([start])
        while queue:
            position = queue.popleft()
            for neighbour in policy._walkable_neighbors(snapshot, position, allow_damaging=False):
                if (neighbour in seen or neighbour in veto
                        or (guarded and _exposed(policy, snapshot, neighbour))):
                    continue
                seen.add(neighbour)
                queue.append(neighbour)
        return frozenset(seen)
    return decision_memo(policy, "angband_finale_battle.reach", snapshot, None, compute)


def _opens_line(policy, snapshot, stand: Position, wall: Position, target: Position) -> bool:
    """Melting ``wall`` would leave a line of fire from ``stand`` to the target where it is.

    The player's projection path (line_of_fire.player_projectable, project_path) with ``wall``
    read as open, within the spells' 18 grids (get_max_range).  The Rocket is aimed at the
    target's cell ('@y,x', me_device_attacks.device_target_key), so the line is any angle, not
    only the stand's ray; the target's spells see the player down the same path."""
    from hengbot import line_of_fire
    return line_of_fire.player_projectable(policy, snapshot, stand, target, opened=(wall,))


def _stand_key(policy, snapshot, held: Battle, target) -> str | None:
    """「なるべく距離をとって相対するように岩石溶解を使って射線を通す。可能なら相手の移動後に射線が通る
    ようにして、先手を取ること。」"""
    from hengbot import sealed_pocket
    from hengbot.policy_constants import WAIT_KEY
    aim = (target.position.y, target.position.x)
    stand = held.stand
    if stand is None or not _open(_grid(snapshot, stand.cell)):
        held.no_stand = None
        stand = held.stand = _choose_stand(policy, snapshot, aim)
    if stand is None:
        return None
    here = (snapshot.player.position.y, snapshot.player.position.x)
    if here != stand.cell:
        goal = Position(*stand.cell)
        step = _route_step(policy, snapshot, lambda position: position == goal)
        if step is None:
            # No walk reaches the stand: the way around it (permanent rock never crossed).
            way = _around_way(policy, snapshot, {goal})
            moved = _around_move(policy, snapshot, way[1], target) if way is not None else None
            if moved is None:
                held.stand = None
            return moved
        key = policy._step_toward(snapshot, step)
        policy.last_reason = STAND_WALK_REASON
        return key
    walls = _walls_between(snapshot, stand)
    if walls is None:
        held.stand = None
        return None
    if walls:
        if _opens_line(policy, snapshot, Position(*here), Position(*walls[0]), target.position):
            # 「可能なら相手の移動後に射線が通るようにして、先手を取ること」 (owner 2026-11-21, LOCKED:
            # 「溶かした時に先手を取られて何も出来ず離脱している場面が問題」): this melt would open the
            # line on the target where it stands, and the melt spends the turn -- the target acts
            # first on the open line.  The wall is kept while the target's own move may open a line
            # (then the hasted player fires first), and past LAST_WALL_HOLD the stand is given up,
            # never opened.
            if stand.held < LAST_WALL_HOLD:
                stand.held += 1
                policy.last_reason = HOLD_REASON
                return WAIT_KEY
            held.refused.add((stand.cell, aim))
            held.stand = None
            return _stand_key(policy, snapshot, held, target)
        if _melt_exposes(policy, snapshot, Position(*walls[0])):
            # Owner 2026-11-24 「射線を通さないように」: this melt opens a strong non-target's line.
            held.refused.add((stand.cell, aim))
            held.stand = None
            return _stand_key(policy, snapshot, held, target)
        stand.held = 0
        return sealed_pocket.melt_at_key(policy, snapshot, Position(*walls[0]), MELT_REASON)
    if stand.held >= OPEN_STAND_WAIT:
        held.stand = None
        return None
    stand.held += 1
    policy.last_reason = HOLD_REASON
    return WAIT_KEY


