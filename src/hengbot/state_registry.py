"""The declared registry of the policy's state (one row per name).

Whole-bot maintainability review 2026-11-17 (N2), owner 2026-11-16 Q4 「決まりを足し検査で確かめる」
and 2026-11-17 Q8: the policy's state grew by name (``self._xxx`` in ``HengbotPolicy.__init__``,
``X = "_xxx"`` constants of the modules, ``getattr``/``setattr``/``hasattr`` on the policy) with no
place saying who owns it and how long it lives.  This is that place.  Data only: nothing here is
read on the decision path, and no behaviour depends on it.

Each row (``State``):

- ``name``: the policy attribute.
- ``owner``: the module whose state it is (the module of its name constant, of its row in a
  partial table, or the one that writes it most).
- ``lifetime``: how long a value is meant to hold, read from where the source clears it:
  ``decision`` (cleared at the decision boundary, ``HengbotPolicy.choose_key``, or named
  ``_decision_*``), ``floor`` (cleared on a floor change: ``floor_visit_memory.VISIT_MEMORIES``,
  the floor-change block of ``ObservationMixin._observe``, the modules' ``forget_floor_visit``),
  ``visit`` (cleared on entering or leaving town in ``_observe``), ``life`` (everything else: it
  holds until its owner changes it, across floors and visits).
- ``destruction``: the player's own *Destruction* forgets it (a row of
  ``monster_memory.DESTRUCTION_FORGETS``).
- ``saved``: a checkpoint keeps it (every policy attribute but ``latch_onset_capture``'s
  ``_CAPTURE_STATE_NAMES`` and the ``_latch_capture_`` names).
- ``purpose``: one line, from the comment at its definition where it has one; a row whose
  definition has no comment says so (to be written by its owner when the state is next touched).

The two partial tables stay where they are and keep what they do; they are columns of this
registry, and ``scripts/state_registry_lint.py`` fails when they disagree with it (a
``VISIT_MEMORIES`` row has lifetime ``floor`` and the same owner; ``destruction`` is set exactly
on the ``DESTRUCTION_FORGETS`` rows, with the same owner), when a state name of the source is not
declared here, when a row names nothing the source has, and when ``saved`` disagrees with the
checkpoint.

Review 2026-11-18 S4 widened it: an attribute assigned on ``self`` anywhere in HengbotPolicy and
its mixins is a state name too; the town visit's forwarded names are rows read from
``town_visit``'s tables (``town_visit_columns``), not copied; a counter-like entry says where the
source resets it today (``RESET_BY``, the "reset by" column).

A new state: add its row here (the lint names the missing one).
"""

